    private readonly Dictionary<string, List<(string TopCategory, string SubCategory)>> _stemIndex;

    public CategorySuggestionService()
    {
        _stemIndex = BuildIndex();
    }

    //таксономията топ категория -> списък подкатегории, за попълване на каскадните падащи менюта
    public Dictionary<string, List<string>> GetTaxonomy()
    {
        return CategoryKeywords.Keys
            .GroupBy(key => key.TopCategory)
            .ToDictionary(group => group.Key, group => group.Select(key => key.SubCategory).ToList());
    }

    //дава до maxResults предложения, по една подкатегория (най-добрата) на топ категория
    public List<CategorySuggestion> Suggest(string title, int maxResults = 3)
    {
        if (string.IsNullOrWhiteSpace(title))
        {
            return new List<CategorySuggestion>();
        }

        var subScores = new Dictionary<(string TopCategory, string SubCategory), double>();

        foreach (var token in Tokenize(title))
        {
            if (Stopwords.Contains(token))
            {
                continue;
            }

            var stem = Stem(token);
            if (!_stemIndex.TryGetValue(stem, out var matches))
            {
                continue;
            }

            var weight = 1.0 / matches.Count;
            foreach (var key in matches)
            {
                subScores[key] = subScores.GetValueOrDefault(key) + weight;
            }
        }

        //за всяка топ категория пази само най-добре съвпадащата подкатегория
        var bestPerTopCategory = new Dictionary<string, (string SubCategory, double Score)>();
        foreach (var ((topCategory, subCategory), score) in subScores)
        {
            if (!bestPerTopCategory.TryGetValue(topCategory, out var existing) || score > existing.Score)
            {
                bestPerTopCategory[topCategory] = (subCategory, score);
            }
        }

        return bestPerTopCategory
            .Select(entry => new CategorySuggestion
            {
                TopCategory = entry.Key,
                SubCategory = entry.Value.SubCategory,
                Score = Math.Round(entry.Value.Score, 2)
            })
            .OrderByDescending(suggestion => suggestion.Score)
            .Take(maxResults)
            .ToList();
    }

    private static Dictionary<string, List<(string, string)>> BuildIndex()
    {
        var index = new Dictionary<string, List<(string, string)>>();

        foreach (var (key, keywords) in CategoryKeywords)
        {
            foreach (var keyword in keywords)
            {
                foreach (var word in Tokenize(keyword))
                {
                    if (Stopwords.Contains(word))
                    {
                        continue;
                    }

                    var stem = Stem(word);
                    if (!index.TryGetValue(stem, out var list))
                    {
                        list = new List<(string, string)>();
                        index[stem] = list;
                    }

                    if (!list.Contains(key))
                    {
                        list.Add(key);
                    }
                }
            }
        }

        return index;
    }

    private static IEnumerable<string> Tokenize(string text)
    {
        return Regex.Matches(text.ToLowerInvariant(), "[а-яa-z0-9]+").Select(match => match.Value);
    }

    //грубо prefix truncation stemming - първите StemLength символа на думата
    private static string Stem(string word)
    {
        return word.Length > StemLength ? word[..StemLength] : word;
    }
